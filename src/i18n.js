let lang = 'th';
try { lang = localStorage.getItem('floodmap.lang') || 'th'; } catch { /* storage blocked */ }
if (!STR[lang]) lang = 'th';

export const getLang = () => lang;

export function t(key, vars = {}) {
  const s = STR[lang][key] ?? STR.th[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
}

export function toggleLang() {
  lang = lang === 'th' ? 'en' : 'th';
  try { localStorage.setItem('floodmap.lang', lang); } catch { /* ignore */ }
  applyI18n();
}

/** Readable message for an API error. */
export function errText(e) {
  const m = String(e?.message || e || '');
  if (m.includes('outside_area')) return t('err.outside_area');
  if (m.includes('path_too_long')) return t('err.path_too_long');
  if (m.includes('not_allowed')) return t('err.not_allowed');
  if (m.includes('not_found')) return t('err.not_found');
  return t('err.send', { m: m.slice(0, 120) });
}
